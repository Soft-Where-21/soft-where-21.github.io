/* ============================================================================
 * 2021 年北航（计算机学院）复试上机 题目二：登机口调整
 * 出处：《北航机试复习指南 2021》第 7~10 页
 *       （作者 慕弋云子，GitHub: Muyiyunzi/BUAA-CS-Codes）
 * 题解文件名：gate.c        编译：gcc -std=c89 -Wall -Wextra
 * ----------------------------------------------------------------------------
 * 【题意】
 *   登机口呈度为 3 的树：根是安检处（编号固定 100），分叉结点编号 ≥ 100，
 *   登机口编号 1~99 且一定是叶结点。已知每个登机口的日均客流量。
 *   在不改变树形（出发时间不变、原在同一登机口的航班不变）的前提下，
 *   只重新分配登机口编号，使所有旅客从安检口到登机口经过的分叉路口总数最少。
 *   调整规则：
 *     ① 登机口按「流量由大到小；流量相同按编号由小到大」排序；
 *     ② 从根开始，按「从上到下、同层从左到右」的顺序依次摆放排序后的登机口。
 *   输出：按排序后的顺序分行输出「调整前的登机口编号 调整后所在位置的登机口编号」。
 * ----------------------------------------------------------------------------
 * 【思路】
 *   1) 树形不变，所以「位置」是固定的：树的每个叶结点（登机口位）就是一个位置。
 *      同一层上的位置到根的距离（经过的分叉数）相同，越靠上的层越近。
 *   2) 于是「总代价最小」= 把流量大的放到靠上的位置 —— 贪心，本质上就是
 *      排序不等式：两个序列同序配对时 Σ a_i·b_i 最大、逆序配对时最小。
 *   3) 位置序列 = 把叶结点按「层次遍历」排出来。层次遍历天然满足
 *      「从上到下、同层从左到右」（孩子按 S1→S2→S3 入队）。
 *   4) 求法只剩两步：登机口按流量排序得 A[]，位置序列记作 B[]，
 *      一一对应（第 i 名放进第 i 个位置）→ 输出 A[i] B[i]。
 * 【实现要点】
 *   - 题面**没给登机口个数**：建树时顺手数一遍叶结点（编号 1~99 的子结点）即可，
 *     这个个数正好等于后面要读的流量信息行数。
 *   - 分叉结点的编号没有规律，不适合直接开二维数组当下标；改用「行」存关系，
 *     每行是一个分叉结点的 3 个孩子。要找某编号所在的行就在 T 行里扫一遍
 *     （T ≤ 100，足够快），这样也不必假设编号范围。
 *   - 层次遍历用数组当队列即可；只需注意：**登机口在入队时就直接记录位置**，
 *     分叉结点才入队。队列另配一个「已入队」标记，正常输入（一棵树）用不到，
 *     但能挡住编号被重复挂到两处的异常数据导致的队列溢出。
 *   - 只有 ≤ 99 个元素要排序，冒泡足够，省去写 qsort 比较函数。
 * 【复杂度】O(T + G^2)，G ≤ 99 为登机口个数，实际耗时可忽略。
 * ============================================================================
 */
#include <stdio.h>

#define MAXL 256   /* 树结点关系条目（分叉结点）≤ 100，留余量 */
#define MAXG 105   /* 登机口 ≤ 99 */

static int fid[MAXL];      /* fid[i]：第 i 行描述的分叉结点编号 */
static int son[MAXL][3];   /* son[i][j]：该分叉结点的第 j 个子结点，-1 表示该位置为空 */

static int slot[MAXG];     /* 层次遍历遇到的登机口序列，即「位置序列」 */
static int ngate;          /* 位置个数（= 树中登机口的个数） */

static int gid[MAXG];      /* 读入的登机口编号 */
static int gflw[MAXG];     /* 对应的日均流量 */

/* 登机口：编号 1~99（分叉结点编号 ≥ 100；-1 表示空位置） */
static int is_gate(int x) { return (x > 0 && x < 100); }

/* 在前 t 行里找「分叉结点编号 == id」的行号，找不到返回 -1 */
static int line_of(int t, int id) {
    int i;
    for (i = 0; i < t; i++)
        if (fid[i] == id) return i;
    return -1;
}

int main(void) {
    int T, i, j, root, head, tail, q[MAXL], inq[MAXL], cur, c, idx, tmp;

    /* 逐组处理：单点测试只跑一组；若文件里有多组也能连续吃下来 */
    while (scanf("%d", &T) == 1) {
        /* ---- 1. 读入树：T 行「R S1 S2 S3」 ---- */
        for (i = 0; i < T; i++)
            scanf("%d %d %d %d", &fid[i], &son[i][0], &son[i][1], &son[i][2]);

        /* ---- 2. 层次遍历：从根（编号 100 所在的那一行）出发 ---- */
        ngate = 0;
        head = tail = 0;
        for (i = 0; i < T; i++) inq[i] = 0;        /* 防重复入队（输入是一棵树，正常不会重） */
        root = line_of(T, 100);
        if (root >= 0) { inq[root] = 1; q[tail++] = root; }
        while (head < tail) {
            cur = q[head++];
            for (j = 0; j < 3; j++) {          /* 从左到右：S1、S2、S3 */
                c = son[cur][j];
                if (c < 0) continue;                  /* 空位置，跳过 */
                if (is_gate(c)) {
                    slot[ngate++] = c;                /* 登机口：按遇到顺序记下位置 */
                } else {
                    idx = line_of(T, c);              /* 分叉结点：找到它的行，入队继续往下 */
                    if (idx >= 0 && !inq[idx]) { inq[idx] = 1; q[tail++] = idx; }
                }
            }
        }

        /* ---- 3. 读入各登机口的流量（行数 = 树中登机口个数） ---- */
        for (i = 0; i < ngate; i++) scanf("%d %d", &gid[i], &gflw[i]);

        /* ---- 4. 排序：流量由大到小；流量相同按登机口编号由小到大 ---- */
        for (i = 0; i < ngate; i++)
            for (j = i + 1; j < ngate; j++)
                if (gflw[j] > gflw[i] || (gflw[j] == gflw[i] && gid[j] < gid[i])) {
                    tmp = gid[i];  gid[i] = gid[j];  gid[j] = tmp;
                    tmp = gflw[i]; gflw[i] = gflw[j]; gflw[j] = tmp;
                }

        /* ---- 5. 一一对应：第 i 名（流量第 i 大）放进第 i 个位置 ---- */
        for (i = 0; i < ngate; i++)
            printf("%d %d\n", gid[i], slot[i]);
    }
    return 0;
}
