/* ============================================================================
 * 北航机试第 2 题「机场送站顺序」     提交文件名：send.c / send.cpp
 * 来源：6 系 2020 年推免复试参考资料（2021 届）机试第 2 题
 * ----------------------------------------------------------------------------
 * 【题意转化】
 *   所有登机口呈树形挂在分叉节点下，安检处是树的根（编号固定为 100）。
 *   电瓶车一次载若干旅客，按下面三条规则决定下车顺序：
 *     1) 挑「当前车上优先级最高」的旅客作为本趟的送站目标（0 优先级最高）；
 *     2) 去目标的路上，凡「登机口直接挂在车所经过的分叉节点上」的旅客，
 *        可顺路下车；同一个分叉节点上有多人时，优先级高的先下；
 *     3) 送完本趟目标后回到第 1 步，从「车现在停的位置」重新出发，直到全部下车。
 *
 *   题面特别注明：送站目的地「实为登机口所属分叉节点」——
 *   即电瓶车只开到【目标登机口的父分叉节点】，登机口自己不进路线。
 *   （样例解说里 sunhui 的路径是 100->102->107->110，到 110 就停了，没开去 12 号口。）
 *
 * 【两个核心结论】
 *   A) 路线 = 树上两点间的唯一简单路径 = 从当前位置上溯到 LCA，再从 LCA 下行到目标。
 *      所以只要会求 LCA，路线就唯一确定了。
 *   B) 下车顺序 = 【车经过分叉节点的先后顺序】，不是优先级顺序！
 *      只有「同一个分叉节点内部」才按优先级排。
 *      铁证：样例里 sunhui 优先级 0（全场最高）最先上车，却第 4 个下车——
 *      因为 wuguo/songyu/huanglei 的登机口 14/13 直接挂在 107 上，车路过 107 时他们先下。
 *
 * 【必须逐趟模拟，不能一次排完】
 *   本趟目标固定是「车上优先级最高的人」，但顺路下车会把别人提前送走，
 *   所以真正的「目标序列」只是「按优先级排序」的一个【子序列】。
 *
 * 【复杂度】
 *   分叉节点 ≤ 100、登机口 ≤ 99，树很小。每趟 O(深度 × 人数)，趟数 ≤ 人数。
 * ============================================================================
 */

#include <stdio.h>
#include <string.h>

#define MAXN 256    /* 树节点总数上限（≤100 分叉 + ≤99 登机口 = 199，留余量） */
#define MAXP 256    /* 旅客数上限 */

/* ---------------------------- 树 ---------------------------- */
static int par[MAXN];   /* par[x] = 节点 x 的父节点；根（100）的父节点为 0 */
static int mark[MAXN];  /* 求 LCA 用：标记 cur 的整条祖先链 */
static int path[MAXN];  /* 本趟车的行驶路线，按「经过顺序」存分叉节点编号 */

/* --------------------------- 旅客 --------------------------- */
static char nm[MAXP][32]; /* 姓名（题面说不超过 20 个字母） */
static int  gate[MAXP];   /* 登机口编号 1~99 */
static int  prio[MAXP];   /* 优先级，数值越小越优先（0 最高） */
static int  used[MAXP];   /* 是否已经下车 */
static int  N;            /* 旅客总数 */

int main(void) {
    int T;                /* 树节点个数 */
    int i, x, y, k;
    int cnt;              /* 本趟路线的节点个数 */
    int cur;              /* 车当前所在节点（初始为安检处 100） */
    int served;           /* 已下车人数 */
    int seg[MAXN], sc;    /* LCA 下行段的临时缓冲，以及它的长度 */
    int best;             /* 在某个节点上挑出的「下一个该下车的人」 */

    /* ---- 1. 读入树：T 行，每行「子节点 父节点」；根的父亲写作 0 ---- */
    if (scanf("%d", &T) != 1) return 0;
    for (i = 0; i < T; i++) {
        int c, p;
        scanf("%d %d", &c, &p);
        par[c] = p;
    }

    /* ---- 2. 读入旅客：姓名 登机口 优先级 ---- */
    scanf("%d", &N);
    for (i = 0; i < N; i++)
        scanf("%s %d %d", nm[i], &gate[i], &prio[i]);

    cur = 100;            /* 电瓶车初始停在安检处（树的根） */
    served = 0;

    /* ---- 3. 逐趟模拟：每趟送一位「目标旅客」，外加沿途顺路的人 ---- */
    while (served < N) {
        int t = -1;
        int nodeT;        /* 本趟目标登机口所属的分叉节点 = 车真正的终点 */

        /* 3.1 选目标：还没下车的旅客里优先级最高的那一位（prio 最小） */
        for (i = 0; i < N; i++)
            if (!used[i] && (t < 0 || prio[i] < prio[t])) t = i;

        /* 登机口是叶子，它的父亲就是车要开到的那个分叉节点 */
        nodeT = par[gate[t]];

        /* 3.2 求路线第一步：把 cur 的整条祖先链打上标记
         *     （cur 自己、它的父亲、祖父…… 一直到根，全部标记）
         *     同时先按「自下而上」的顺序把上行段记进 path。
         *     终点条件 x != 0 是因为根的父亲是 0，遇到 0 说明已到顶。 */
        memset(mark, 0, sizeof mark);
        cnt = 0;
        for (x = cur; x != 0; x = par[x]) {
            mark[x] = 1;
            path[cnt++] = x;
        }

        /* 3.3 从目标节点往上走，撞到的第一个已被标记的节点就是 LCA
         *     （cur 的祖先链已全标记，所以两边祖先的第一次「相遇点」即最近公共祖先）
         *     循环结束后 y 就是 LCA。 */
        y = nodeT;
        while (!mark[y]) y = par[y];

        /* 3.4 补上「下行段」：目标节点向上到 LCA（不含 LCA）这一段。
         *     上溯时收集到的是自下而上，所以要倒着接到路线尾部，
         *     这样整条 path 恰好就是「车实际经过的顺序」。
         *     特例：nodeT 本身就是 LCA（或 nodeT == cur）时 sc == 0，
         *     路径退化成单个节点，代码依然正确，不会越界。 */
        sc = 0;
        for (x = nodeT; x != y; x = par[x]) seg[sc++] = x;
        while (sc > 0) path[cnt++] = seg[--sc];

        /* 3.5 沿路线「经过顺序」逐节点安排顺路旅客下车 */
        for (k = 0; k < cnt; k++) {
            /* 一个分叉节点最多挂 4 个登机口，可能有多人都顺路。
             * 反复挑「优先级最高」的那位输出，就实现了
             * 题面要求的「同一分叉结点上有多个顺路旅客时，优先级高的先下车」。 */
            for (;;) {
                best = -1;
                for (i = 0; i < N; i++)
                    if (!used[i] && par[gate[i]] == path[k]
                        && (best < 0 || prio[i] < prio[best]))
                        best = i;
                if (best < 0) break;            /* 这个节点上没人顺路了 */
                printf("%s %d\n", nm[best], gate[best]);
                used[best] = 1;
                served++;
            }
        }

        /* 3.6 本趟结束：车停在目标登机口所属的那个分叉节点上，作为下一趟的起点 */
        cur = nodeT;
    }
    return 0;
}

